import os
import sys
import shutil
import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor, Mm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import parse_xml, OxmlElement
from docx.oxml.ns import nsdecls, qn

if sys.platform == 'win32':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPORT_NAME_1 = os.path.join(SCRIPT_DIR, "ГайнановГарифуллин_ПР5_АССН.docx")
REPORT_NAME_2 = os.path.join(SCRIPT_DIR, "ЭАС-514С_АССН_Гайнанов_Гарифуллин_ПР5.docx")

def build_pr5_report():
    print("=== Генерация академического отчёта по Практической работе № 5 (АСУСН) ===")

    doc = Document()

    # Параметры страницы: А4, стандартные поля (Левое 30 мм, Правое 15 мм, Верх/Низ 20 мм)
    for section in doc.sections:
        section.page_width = Mm(210)
        section.page_height = Mm(297)
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)
        section.left_margin = Mm(30)
        section.right_margin = Mm(15)

    def set_cell_margins(cell, top=100, bottom=100, left=140, right=140):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = parse_xml(f'<w:tcMar {nsdecls("w")}>'
                          f'<w:top w:w="{top}" w:type="dxa"/>'
                          f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
                          f'<w:left w:w="{left}" w:type="dxa"/>'
                          f'<w:right w:w="{right}" w:type="dxa"/>'
                          f'</w:tcMar>')
        tcPr.append(tcMar)

    def set_table_borders(table, color="000000"):
        tblPr = table._tbl.tblPr
        borders = parse_xml(f'<w:tblBorders {nsdecls("w")}>'
                            f'<w:top w:val="single" w:sz="6" w:space="0" w:color="{color}"/>'
                            f'<w:bottom w:val="single" w:sz="6" w:space="0" w:color="{color}"/>'
                            f'<w:insideH w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
                            f'<w:insideV w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
                            f'<w:left w:val="single" w:sz="6" w:space="0" w:color="{color}"/>'
                            f'<w:right w:val="single" w:sz="6" w:space="0" w:color="{color}"/>'
                            f'</w:tblBorders>')
        tblPr.append(borders)

    def add_p(text, bold_prefix="", italic=False, space_after=4, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=12.5):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.line_spacing = 1.15
        if indent > 0:
            p.paragraph_format.first_line_indent = Mm(indent)
        p.alignment = align

        if bold_prefix:
            r_pre = p.add_run(bold_prefix)
            r_pre.font.name = "Times New Roman"
            r_pre.font.size = Pt(12)
            r_pre.bold = True
            r_pre.font.color.rgb = RGBColor(15, 23, 42)

        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(12)
        run.font.color.rgb = RGBColor(30, 41, 59)
        run.italic = italic
        return p

    def add_title(text, level=1):
        p = doc.add_paragraph()
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.bold = True

        if level == 1:
            p.paragraph_format.space_before = Pt(16)
            p.paragraph_format.space_after = Pt(6)
            run.font.size = Pt(14)
            run.font.color.rgb = RGBColor(15, 23, 42)
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        elif level == 2:
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(4)
            run.font.size = Pt(12.5)
            run.font.color.rgb = RGBColor(30, 41, 59)
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        else:
            p.paragraph_format.space_before = Pt(8)
            p.paragraph_format.space_after = Pt(3)
            run.font.size = Pt(12)
            run.font.color.rgb = RGBColor(51, 65, 85)
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        return p

    def add_caption(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(10.5)
        run.bold = True
        run.font.color.rgb = RGBColor(30, 41, 59)
        return p

    # =========================================================================
    # ТИТУЛЬНЫЙ ЛИСТ
    # =========================================================================
    p_header = doc.add_paragraph()
    p_header.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_hdr = p_header.add_run("Министерство науки и высшего образования Российской Федерации\n"
                             "ФГБОУ ВО «Уфимский университет науки и технологий»\n"
                             "Кафедра автоматизированных систем управления\n")
    r_hdr.font.name = "Times New Roman"
    r_hdr.font.size = Pt(11)
    r_hdr.bold = True

    for _ in range(3):
        doc.add_paragraph()

    p_center = doc.add_paragraph()
    p_center.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_rep = p_center.add_run("ОТЧЕТ ПО ПРАКТИЧЕСКОЙ РАБОТЕ № 5\n")
    r_rep.font.name = "Times New Roman"
    r_rep.font.size = Pt(16)
    r_rep.bold = True

    r_disc = p_center.add_run("по дисциплине: «Автоматизированные системы специального назначения»\n\n")
    r_disc.font.name = "Times New Roman"
    r_disc.font.size = Pt(13)

    r_theme = p_center.add_run("на тему: «Составление плана технического обслуживания\nи регламента»\n")
    r_theme.font.name = "Times New Roman"
    r_theme.font.size = Pt(14)
    r_theme.bold = True

    r_obj = p_center.add_run("(на примере автоматизированной системы специального назначения\nнефтеперекачивающей станции — АС СН НПС)\n")
    r_obj.font.name = "Times New Roman"
    r_obj.font.size = Pt(12)
    r_obj.italic = True

    for _ in range(4):
        doc.add_paragraph()

    p_sign = doc.add_paragraph()
    p_sign.paragraph_format.left_indent = Mm(90)
    p_sign.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r_sign = p_sign.add_run("Выполнили:\n"
                            "студенты гр. ЭАС-514С\n"
                            "Гайнанов Данил Ильдарович\n"
                            "Гарифуллин Карим Рамилевич\n\n"
                            "Проверил:\n"
                            "Антонов В.В.\n")
    r_sign.font.name = "Times New Roman"
    r_sign.font.size = Pt(12)

    for _ in range(3):
        doc.add_paragraph()

    p_city = doc.add_paragraph()
    p_city.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_city = p_city.add_run("Уфа, 2026 г.")
    r_city.font.name = "Times New Roman"
    r_city.font.size = Pt(12)

    doc.add_page_break()

    # =========================================================================
    # РАЗДЕЛ: ЦЕЛЬ РАБОТЫ И ФОРМИРУЕМЫЕ КОМПЕТЕНЦИИ
    # =========================================================================
    add_title("ЦЕЛЬ РАБОТЫ", level=1)
    add_p(
        "Освоить научно-методические основы и практические навыки разработки комплексного плана технического "
        "обслуживания (ТО), технологических регламентов и метрологического обеспечения для автоматизированных систем "
        "управления специального назначения (АС СН) на примере технологического комплекса нефтеперекачивающей "
        "станции (НПС); научиться определять оптимальную периодичность регламентных работ с учетом критичности "
        "оборудования и требований промышленной безопасности; разработать подробные операционные карты ТО для "
        "полевого, микропроцессорного и исполнительного уровней; построить сбалансированный годовой календарный график ТО; "
        "сформировать инструкцию по действиям оперативного и ремонтного персонала в нештатных ситуациях; "
        "рассчитать научно обоснованную потребность в аварийном комплекте запасных частей, инструмента и принадлежностей (ЗИП), "
        "а также сформировать парк образцовых калибровочных средств измерений."
    )
    add_p(
        "Формируемые компетенции: способность организовывать и осуществлять надежную техническую эксплуатацию, "
        "метрологический контроль, техническое обслуживание и ремонт автоматизированных систем специального назначения, "
        "обеспечивая нормативный коэффициент готовности системы не менее 0,999 в условиях непрерывного опасного производства."
    )

    # =========================================================================
    # РАЗДЕЛ: ТЕОРЕТИЧЕСКИЕ ОСНОВЫ И НОРМАТИВНАЯ БАЗА
    # =========================================================================
    add_title("1. ТЕОРЕТИЧЕСКИЕ ОСНОВЫ ТЕХНИЧЕСКОЙ ЭКСПЛУАТАЦИИ АС СН", level=1)
    add_p(
        "Техническая эксплуатация АС СН объектов магистрального трубопроводного транспорта нефти регламентируется "
        "системой государственных стандартов (ГОСТ 18322-2016 «Система технического обслуживания и ремонта техники. "
        "Термины и определения», ГОСТ Р МЭК 61508 «Функциональная безопасность систем электрических, электронных, "
        "программируемых электронных, связанных с безопасностью»), а также отраслевыми регламентами ПАО «Транснефть» "
        "(ОР-13.010.00-КТН-002-19). Специфика систем специального назначения заключается в жестких требованиях "
        "к отказоустойчивости, функциональной безопасности (уровень полноты безопасности SIL2/SIL3) и взрывозащищенности."
    )
    add_p(
        "В практике эксплуатации АС СН применяется комбинированная стратегия обслуживания, сочетающая планово-предупредительный "
        "подход (ППР) и обслуживание по фактическому техническому состоянию (RCM — Reliability-Centered Maintenance). "
        "Система ТО включает следующие взаимосвязанные виды работ:",
        bold_prefix="Классификация видов ТО: "
    )
    add_p(
        "1. Ежедневное обслуживание (ЕО) — непрерывный и ежесменный оперативный контроль работоспособности КТС, "
        "визуальный осмотр целостности шкафов, панелей индикации ПЛК, ИБП, серверов SCADA, контроль отсутствия утечек "
        "нефти по импульсным линиям датчиков, проверка отсутствия аварийных алертов на мнемосхемах.\n"
        "2. Еженедельное / двухнедельное обслуживание (ТО-1) — детальный осмотр полевых приборов КИПиА, контроль кабельных "
        "вводов и заземления, проверка плавности хода исполнительных механизмов, контроль рабочих напряжений вторичного питания.\n"
        "3. Ежемесячное обслуживание (ТО-2) — профилактический контроль метрологических характеристик датчиков, "
        "проверка нулевых точек («Zero Trim»), диагностика состояния дублированных контроллеров Regul R500 и шин связи, "
        "тестирование аккумуляторных батарей ИБП под нагрузкой, анализ журналов событий SCADA.\n"
        "4. Ежеквартальное обслуживание (ТО-3) — углубленная профилактика микропроцессорной техники, обеспыливание шкафов, "
        "протяжка клеммных и болтовых соединений, проверка срабатывания аварийных сигнализаций и блокировок, смазка узлов приводов.\n"
        "5. Ежегодное регламентное обслуживание (ТО-4) — капитальная ревизия оборудования, периодическая государственная "
        "поверка средств измерений в аккредитованной лаборатории метрологии, комплексное тестирование алгоритмов противоаварийной "
        "защиты (ПАЗ), измерение сопротивления изоляции кабелей, резервное копирование и аудит программного обеспечения.\n"
        "6. Внеплановое обслуживание (АВР) — аварийно-восстановительные работы при возникновении отказов, инцидентов "
        "или повреждений технических средств с немедленным вызовом оперативной бригады КИПиА и АСУ ТП."
    )

    # Вставка Рис. 1: Иерархическая структура КТС
    img_tree = os.path.join(SCRIPT_DIR, "pr5_equipment_tree.png")
    if os.path.exists(img_tree):
        doc.add_paragraph()
        p_img = doc.add_paragraph()
        p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_img.paragraph_format.space_before = Pt(6)
        p_img.paragraph_format.space_after = Pt(2)
        run_img = p_img.add_run()
        run_img.add_picture(img_tree, width=Inches(6.4))
        add_caption("Рисунок 1 — Иерархическая структура комплекса технических средств (КТС) АС СН НПС и распределение зон обслуживания")

    # =========================================================================
    # ЭТАП 1: ИНВЕНТАРИЗАЦИЯ ОБОРУДОВАНИЯ
    # =========================================================================
    add_title("2. ЭТАП 1. ИНВЕНТАРИЗАЦИЯ И СПЕЦИФИКАЦИЯ ОБОРУДОВАНИЯ АС СН НПС", level=1)
    add_p(
        "В соответствии с техническим заданием проведен полный структурный аудит и инвентаризация комплекса "
        "технических средств (КТС) автоматизированной системы специального назначения магистральной нефтеперекачивающей "
        "станции. Оборудование разделено на функциональные категории, для каждой единицы определены место установки "
        "и уровень критичности с точки зрения безопасности технологического процесса (Таблица 1)."
    )

    add_caption("Таблица 1 — Инвентаризационная ведомость оборудования АС СН НПС")

    from pr5_maintenance_planner import EQUIPMENT_DATA

    t1 = doc.add_table(rows=1, cols=7)
    t1.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(t1)

    hdr_cells1 = t1.rows[0].cells
    hdr_titles1 = ["Поз. ID", "Наименование оборудования", "Тип / Модель", "Категория КТС", "Кол-во", "Место установки", "Критичность"]
    col_widths1 = [Mm(18), Mm(42), Mm(32), Mm(26), Mm(14), Mm(38), Mm(22)]

    for i, title in enumerate(hdr_titles1):
        hdr_cells1[i].text = title
        set_cell_margins(hdr_cells1[i], top=80, bottom=80, left=90, right=90)
        p = hdr_cells1[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        r = p.runs[0]
        r.font.name = "Times New Roman"
        r.font.size = Pt(9.5)
        r.font.bold = True
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="E2E8F0"/>')
        hdr_cells1[i]._tc.get_or_add_tcPr().append(shading)

    for eq in EQUIPMENT_DATA:
        row_cells = t1.add_row().cells
        vals = [eq["id"], eq["name"], eq["model"], eq["category"], str(eq["qty"]), eq["location"], eq["criticality"]]
        for i, val in enumerate(vals):
            row_cells[i].text = val
            set_cell_margins(row_cells[i], top=50, bottom=50, left=80, right=80)
            p = row_cells[i].paragraphs[0]
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(1)
            if i in [0, 4, 6]:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r = p.runs[0]
            r.font.name = "Times New Roman"
            r.font.size = Pt(8.5)

    for row in t1.rows:
        for i, w in enumerate(col_widths1):
            row.cells[i].width = w

    add_p(
        "Анализ ведомости показывает, что критическое ядро АС СН составляют датчики давления Метран-150-TG (на выкиде "
        "магистральных насосных агрегатов давление достигает 6,4 МПа), датчики вибрации ВК-310В, дублированный "
        "контроллер противоаварийной защиты Regul R500S уровня SIL3 и электроприводы магистральных задвижек Auma SA 14.2. "
        "Отказ любого из этих компонентов без надлежащего резервирования и превентивного ТО способен вызвать аварийную остановку "
        "перекачки нефти с колоссальным экономическим ущербом.",
        space_after=8
    )

    # =========================================================================
    # ЭТАП 2: ВИДЫ И ПЕРИОДИЧНОСТЬ ТО
    # =========================================================================
    add_title("3. ЭТАП 2. ОПРЕДЕЛЕНИЕ ВИДОВ, ПЕРИОДИЧНОСТИ И ТРУДОЕМКОСТИ ТО", level=1)
    add_p(
        "Периодичность и состав работ по ТО определены на основе рекомендаций заводов-изготовителей, требований правил "
        "безопасности в нефтяной промышленности (ФНП) и статистических данных по наработке на отказ $T_0$ (MTBF). "
        "Штучная трудоемкость каждой операции рассчитана по типовым нормам времени на техническое обслуживание "
        "средств КИПиА и микропроцессорных систем автоматизации. В таблице 2 представлена развернутая матрица регламентов."
    )

    add_caption("Таблица 2 — Ведомость видов, периодичности и нормативной трудоемкости ТО КТС АС СН НПС")

    from pr5_maintenance_planner import calculate_labor_statistics
    stats = calculate_labor_statistics()

    t2 = doc.add_table(rows=1, cols=8)
    t2.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(t2)

    hdr_cells2 = t2.rows[0].cells
    hdr_titles2 = ["Поз. ID", "Оборудование", "Вид ТО", "Периодичность", "Кол-во", "Ед., чел·ч", "Год, чел·ч", "Исполнитель"]
    col_widths2 = [Mm(16), Mm(42), Mm(16), Mm(26), Mm(12), Mm(18), Mm(18), Mm(44)]

    for i, title in enumerate(hdr_titles2):
        hdr_cells2[i].text = title
        set_cell_margins(hdr_cells2[i], top=80, bottom=80, left=80, right=80)
        p = hdr_cells2[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        r = p.runs[0]
        r.font.name = "Times New Roman"
        r.font.size = Pt(9.5)
        r.font.bold = True
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="E2E8F0"/>')
        hdr_cells2[i]._tc.get_or_add_tcPr().append(shading)

    for row_data in stats["table_rows"]:
        row_cells = t2.add_row().cells
