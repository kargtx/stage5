# -*- coding: utf-8 -*-
"""
Генератор классического отчета УУНиТ (Пояснительной записки) по Части 2 ЛР:
«Детальный бизнес-сценарий (ДБС) оказания услуг программной модификации
блоков управления двигателем (чип-тюнинг) в КИС Автосервис»

Требования:
- СТРОГО БЕЗ ВЕРХНИХ ШАПОК / КОЛОНТИТУЛОВ (обычный классический отчет УУНиТ по СТП УГАТУ)
- Титульный лист отчета УУНиТ (2026 г., студенты Гайнанов Д.И., Гарифуллин К.Р., преп. Демченко М.С.)
- Официальный Лист Задания ЧАСТЬ 2
- Автособираемое Оглавление MS Word (TOC)
- Введение
- Раздел 1. Назначение и основные положения ДБС (Бизнес-цели, KPI, ограничения, функциональность, термины)
- Раздел 2. Моделирование бизнес-процесса оказания услуг чип-тюнинга:
    2.1 Функциональная мнемосхема (Рисунок 1)
    2.2 Динамическая модель подпроцесса 1 Гайнанова Д.И. (Рисунок 2)
    2.3 Динамическая модель подпроцесса 2 Гарифуллина К.Р. (Рисунок 3)
    2.4 Общая сквозная модель BPMN 2.0 на 5 дорожек (Рисунок 4)
    2.5 Реляционная модель данных ERD в 3NF (Рисунок 5)
    2.6 Матрицы распределения ответственности (Таблицы 2 и 3 с отметками +)
- Раздел 3. Детальный бизнес-сценарий по шагам процесса:
    3.1 Подпроцесс 1 (Гайнанов Д.И., шаги 1.1 - 1.10)
    3.2 Подпроцесс 2 (Гарифуллин К.Р., шаги 2.1 - 2.10)
    Для каждого шага:
      - Спецификация шага (4x2: Условия, Исполнитель, Вход, Выход)
      - Назначение
      - Описание действий
      - Значимые атрибуты объекта шага (4 колонки: Атрибут (Поле БД) | Таблица ERD | Описание | Рекомендации по заполнению)
      - Требуемое изменение функциональности
      - Требования к интеграции
- Заключение
- Список используемых источников
- Оформление: строго черный шрифт Times New Roman, чистые белые таблицы без заливки, 1pt границы
"""

import os
import shutil
import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor, Mm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import parse_xml, OxmlElement
from docx.oxml.ns import nsdecls, qn

def create_uunit_report():
    print("=== НАЧАЛО ГЕНЕРАЦИИ КЛАССИЧЕСКОГО ОТЧЕТА УУНИТ (БЕЗ ШАПОК) ===")
    
    script_dir = os.path.dirname(os.path.abspath(__file__))
    dbs_dir = os.path.abspath(os.path.join(script_dir, ".."))
    kis_dir = os.path.abspath(os.path.join(dbs_dir, ".."))
    
    out_docx_1 = os.path.join(dbs_dir, "Отчет_по_ЛР_Часть_2_УУНиТ_Гайнанов_Гарифуллин.docx")
    out_docx_2 = os.path.join(kis_dir, "Отчет_по_ЛР_Часть_2_УУНиТ_Гайнанов_Гарифуллин.docx")
    out_docx_old = os.path.join(dbs_dir, "Отчет_ЛР_Часть2_ДБС_ЧипТюнинг_Гайнанов_Гарифуллин.docx")
    
    doc = Document()
    
    # -------------------------------------------------------------------------
    # НАСТРОЙКА СТРАНИЦЫ (СТП УГАТУ: левое 30 мм, правое 15 мм, верх/низ 20 мм)
    # СТРОГО БЕЗ ВЕРХНИХ КОЛОНТИТУЛОВ (БЕЗ ШАПОК)!
    # -------------------------------------------------------------------------
    for s in doc.sections:
        s.page_width = Mm(210)
        s.page_height = Mm(297)
        s.top_margin = Mm(20)
        s.bottom_margin = Mm(20)
        s.left_margin = Mm(30)
        s.right_margin = Mm(15)
        # Очищаем колонтитулы полностью
        s.header.is_linked_to_previous = False
        for p in s.header.paragraphs:
            p.text = ""
        while len(s.header.tables) > 0:
            s.header._element.remove(s.header.tables[0]._element)
            
    # Включаем автоматическое обновление оглавления при открытии
    settings = doc.settings._element
    settings.append(parse_xml(r'<w:updateFields %s w:val="true"/>' % nsdecls('w')))

    COLOR_BLACK = RGBColor(0, 0, 0)

    # -------------------------------------------------------------------------
    # ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ ФОРМАТИРОВАНИЯ
    # -------------------------------------------------------------------------
    def add_p(text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_before=0, space_after=4, indent=True, italic=False, bold=False):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.line_spacing = 1.15
        if indent:
            p.paragraph_format.first_line_indent = Mm(12.5)
        else:
            p.paragraph_format.first_line_indent = Mm(0)
            
        if text:
            r = p.add_run(text)
            r.font.name = "Times New Roman"
            r.font.size = Pt(12)
            r.font.color.rgb = COLOR_BLACK
            r.bold = bold
            r.italic = italic
        return p

    def add_bullet(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.15
        p.paragraph_format.left_indent = Mm(18)
        p.paragraph_format.first_line_indent = Mm(-5.5)
        r = p.add_run("— " + text)
        r.font.name = "Times New Roman"
        r.font.size = Pt(12)
        r.font.color.rgb = COLOR_BLACK
        return p

    def add_h(text, level=1):
        h = doc.add_heading(level=level)
        h.paragraph_format.keep_with_next = True
        h.paragraph_format.first_line_indent = Mm(0)
        h.paragraph_format.line_spacing = 1.15
        run = h.add_run(text)
        run.font.name = "Times New Roman"
        run.bold = True
        run.font.color.rgb = COLOR_BLACK
        if level == 1:
            h.paragraph_format.space_before = Pt(16)
            h.paragraph_format.space_after = Pt(6)
            h.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run.font.size = Pt(14)
        elif level == 2:
            h.paragraph_format.space_before = Pt(12)
            h.paragraph_format.space_after = Pt(4)
            h.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run.font.size = Pt(13)
        elif level == 3:
            h.paragraph_format.space_before = Pt(10)
            h.paragraph_format.space_after = Pt(3)
            h.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run.font.size = Pt(12)
        else:
            h.paragraph_format.space_before = Pt(8)
            h.paragraph_format.space_after = Pt(2)
            h.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run.font.size = Pt(12)
        return h

    def add_caption(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.first_line_indent = Mm(0)
        r = p.add_run(text)
        r.font.name = "Times New Roman"
        r.font.size = Pt(11)
        r.italic = True
        r.font.color.rgb = COLOR_BLACK
        return p

    def add_table_caption(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.first_line_indent = Mm(0)
        r = p.add_run(text)
        r.font.name = "Times New Roman"
        r.font.size = Pt(11)
        r.bold = True
        r.font.color.rgb = COLOR_BLACK
        return p

    def set_cell_margins(cell, top=100, bottom=100, left=140, right=140):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = parse_xml(
            f'<w:tcMar {nsdecls("w")}>'
            f'<w:top w:w="{top}" w:type="dxa"/>'
            f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
            f'<w:left w:w="{left}" w:type="dxa"/>'
            f'<w:right w:w="{right}" w:type="dxa"/>'
            f'</w:tcMar>'
        )
        tcPr.append(tcMar)

    def format_table(table, col_widths, grid_cols=None):
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        tblPr = table._tbl.tblPr
        
        # Черные тонкие рамки
        tblBorders = parse_xml(
            f'<w:tblBorders {nsdecls("w")}>'
            f'<w:top w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:bottom w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:left w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:right w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'</w:tblBorders>'
        )
        tblPr.append(tblBorders)

        if grid_cols:
            grid_xml = f'<w:tblGrid {nsdecls("w")}>'
            for gw in grid_cols:
                grid_xml += f'<w:gridCol w:w="{gw}"/>'
            grid_xml += '</w:tblGrid>'
            if table._tbl.tblGrid is not None:
                table._tbl.remove(table._tbl.tblGrid)
            table._tbl.tblPr.addnext(parse_xml(grid_xml))

        for row in table.rows:
            trPr = row._tr.get_or_add_trPr()
            trPr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
            for j, cell in enumerate(row.cells):
                cell.width = col_widths[j]
                set_cell_margins(cell, top=80, bottom=80, left=120, right=120)
                tcPr = cell._tc.get_or_add_tcPr()
                # Чистый белый фон без заливки
                tcPr.append(parse_xml(f'<w:shd {nsdecls("w")} w:fill="FFFFFF" w:val="clear"/>'))
                for p in cell.paragraphs:
                    p.paragraph_format.space_before = Pt(1)
                    p.paragraph_format.space_after = Pt(1)
                    p.paragraph_format.line_spacing = 1.05
                    p.paragraph_format.first_line_indent = Mm(0)
                    for r in p.runs:
                        r.font.name = "Times New Roman"
                        r.font.size = Pt(10)
                        r.font.color.rgb = COLOR_BLACK

    def add_image_figure(img_file, caption_text, width_inches=6.2):
        img_path = os.path.join(dbs_dir, img_file)
        if os.path.exists(img_path):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(8)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.first_line_indent = Mm(0)
            r = p.add_run()
            r.add_picture(img_path, width=Inches(width_inches))
            add_caption(caption_text)
        else:
            print(f"[!] Файл изображения не найден: {img_path}")

    # -------------------------------------------------------------------------
    # 1. ТИТУЛЬНЫЙ ЛИСТ ОТЧЕТА ПО СТП УГАТУ (ГОД 2026)
    # -------------------------------------------------------------------------
    print("1. Формирование титульного листа отчета...")
    add_p("Министерство науки и высшего образования Российской Федерации", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=1, indent=False, bold=True)
    add_p("Федеральное государственное бюджетное образовательное учреждение высшего образования", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=1, indent=False)
    add_p("«УФИМСКИЙ УНИВЕРСИТЕТ НАУКИ И ТЕХНОЛОГИЙ»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=1, indent=False, bold=True)
    add_p("Кафедра автоматизированных систем управления", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=40, indent=False)

    add_p("ОТЧЕТ ПО ЛАБОРАТОРНЫМ РАБОТАМ", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=4, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(16)
    add_p("по дисциплине «Корпоративные информационные системы»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=4, indent=False)
    doc.paragraphs[-1].runs[0].font.size = Pt(13)
    add_p("ЧАСТЬ 2", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=16, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(14)

    add_p("Тема: «Детальный бизнес-сценарий (ДБС) оказания услуг программной модификации блоков управления двигателем (чип-тюнинг) в КИС Автосервис»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=60, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(13)

    add_p("Выполнили:", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False, bold=True)
    add_p("студенты группы ЭАС-514С", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False)
    add_p("Гайнанов Д. И.  / _________________ /", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False)
    add_p("Гарифуллин К. Р.  / _________________ /", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False)
    add_p("«___» ________________ 2026 г.", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=20, indent=False)

    add_p("Проверил:", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False, bold=True)
    add_p("ст. преподаватель кафедры АСУ", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False)
    add_p("Демченко М. С.  / _________________ /", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1, indent=False)
    add_p("«___» ________________ 2026 г.", align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=80, indent=False)

    add_p("Уфа — 2026 г.", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=0, indent=False, bold=True)
    doc.add_page_break()

    # -------------------------------------------------------------------------
    # 2. ОФИЦИАЛЬНЫЙ ЛИСТ ЗАДАНИЯ ЧАСТЬ 2
    # -------------------------------------------------------------------------
    print("2. Формирование листа задания...")
    add_p("Федеральное государственное бюджетное образовательное учреждение высшего образования", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=1, indent=False)
    doc.paragraphs[-1].runs[0].font.size = Pt(9.5)
    add_p("«Уфимский университет науки и технологий»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=1, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(11)
    add_p("Кафедра автоматизированных систем управления", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=8, indent=False)
    doc.paragraphs[-1].runs[0].font.size = Pt(10)

    add_p("ЗАДАНИЕ", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=2, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(13)
    add_p("на лабораторные работы по дисциплине «Корпоративные информационные системы» ЧАСТЬ 2", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=8, indent=False, bold=True)
    doc.paragraphs[-1].runs[0].font.size = Pt(11)

    # Таблица студентов задания
    t_z0 = doc.add_table(rows=2, cols=6)
    headers_z0 = [
        ("Студент", True), ("Гайнанов Д.И., Гарифуллин К.Р.", True),
        ("Группа", True), ("ЭАС-514С", True),
        ("Консультант", True), ("Демченко М.С.", True)
    ]
    sub_z0 = [("", False), ("Фамилия И.О.", False), ("", False), ("номер группы", False), ("", False), ("Фамилия И.О.", False)]
    for j, (txt, b) in enumerate(headers_z0):
        c = t_z0.rows[0].cells[j]
        c.paragraphs[0].text = txt
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        if b: c.paragraphs[0].runs[0].bold = True
    for j, (txt, b) in enumerate(sub_z0):
        c = t_z0.rows[1].cells[j]
        c.paragraphs[0].text = txt
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        if txt: c.paragraphs[0].runs[0].italic = True
    format_table(t_z0, [Mm(25), Mm(50), Mm(20), Mm(25), Mm(25), Mm(25)], ["1400", "2800", "1100", "1400", "1400", "1400"])

    add_p("", space_after=4, indent=False)

    # Таблица содержания задания
    t_z1 = doc.add_table(rows=4, cols=2)
    z1_data = [
        ("1. Тема:", "«Детальный бизнес-сценарий (ДБС) оказания услуг программной модификации блоков управления двигателем (чип-тюнинг) в КИС Автосервис»"),
        ("2. Основное содержание:", "В рамках лабораторных работ ЧАСТЬ 1 сформирована технико-экономическая характеристика объекта автоматизации и построена ERD. Далее разработан «Детальный бизнес-сценарий (ДБС) процесса оказания услуг чип-тюнинга автомобиля» в соответствии с корпоративным шаблоном ДБС и СТП УГАТУ. Включены: общая схема БП на 5 ролей, матрицы ответственности, пошаговая спецификация 20 шагов процесса с таблицами значимых атрибутов базы данных (3NF), требованиями к функционалу и интеграции. Все схемы разработаны в MS Visio."),
        ("3. Исходные данные:", "Вариант № 102 «Автосервис чип-тюнинга BMW102»; результаты ЧАСТИ 1 (подпроцесс оформления заявки и утверждения наряд-заказа — студент Гайнанов Д.И.; подпроцесс исполнения наряд-заказа с комментарием мастера и выдачи акта — студент Гарифуллин К.Р.); нормативные стандарты СТО 521.18.107-2007, СТО 521.18.158-2018, регламенты ISTA/D и ISTA/P BMW AG."),
        ("4. Требования к оформлению:", "4.1 Пояснительная записка к отчету оформляется в текстовом редакторе MS Word в соответствии с СТП УГАТУ. Обязательно автособираемое Оглавление.\n4.2 В ПЗ содержатся разделы: Титульный лист, Лист Задания, Оглавление, Введение, Раздел 1 (Назначение и основные положения), Раздел 2 (Моделирование бизнес-процесса), Раздел 3 (Детальное описание 20 шагов БП), Заключение, Список используемых источников.\n4.3 Срок сдачи: 2026 г.")
    ]
    for idx, (k, v) in enumerate(z1_data):
        row = t_z1.rows[idx]
        row.cells[0].paragraphs[0].text = k
        row.cells[0].paragraphs[0].runs[0].bold = True
        row.cells[1].paragraphs[0].text = v
    format_table(t_z1, [Mm(45), Mm(120)], ["2500", "7000"])

    add_p("", space_after=6, indent=False)
    add_p("Руководитель: __________________ М.С. Демченко          Студенты: _________________ Гайнанов Д.И., Гарифуллин К.Р.", align=WD_ALIGN_PARAGRAPH.LEFT, space_after=0, indent=False)
    doc.add_page_break()

    # -------------------------------------------------------------------------
    # 3. АВТОСОБИРАЕМОЕ ОГЛАВЛЕНИЕ MS WORD (TOC)
    # -------------------------------------------------------------------------
    print("3. Вставка автособираемого Оглавления...")
    add_h("Оглавление", level=1)
    p_toc = doc.add_paragraph()
    p_toc.paragraph_format.space_before = Pt(6)
    p_toc.paragraph_format.space_after = Pt(12)
    p_toc.paragraph_format.first_line_indent = Mm(0)
    # Поле автособираемого оглавления
    fld = parse_xml(r'<w:fldSimple %s w:instr="TOC \o &quot;1-3&quot; \h \z \u"/>' % nsdecls('w'))
    p_toc._p.append(fld)
    doc.add_page_break()

    # -------------------------------------------------------------------------
    # 4. ВВЕДЕНИЕ
    # -------------------------------------------------------------------------
