import shutil
import docx
from docx import Document
from docx.shared import Pt, RGBColor, Mm, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn

def generate_part1_report():
    print("=== НАЧАЛО ГЕНЕРАЦИИ ОТЧЕТА ПО ЛР КИС ЧАСТЬ 1 (УУНиТ, 2026) ===")

    base_dir = r"c:\Users\danch\OneDrive\Рабочий стол\stage5\КИС\лр часть 1"
    kis_dir = r"c:\Users\danch\OneDrive\Рабочий стол\stage5\КИС"
    
    out_docx_part1_local = os.path.join(base_dir, "Отчет_по_ЛР_Часть_1_УУНиТ_Гайнанов_Гарифуллин.docx")
    out_docx_part1_root = os.path.join(kis_dir, "Отчет_по_ЛР_Часть_1_УУНиТ_Гайнанов_Гарифуллин.docx")

    doc = Document()

    # -------------------------------------------------------------------------
    # НАСТРОЙКА СТРАНИЦЫ (СТП УГАТУ: левое 30 мм, правое 15 мм, верх/низ 20 мм)
    # -------------------------------------------------------------------------
    for s in doc.sections:
        s.page_width = Mm(210)
        s.page_height = Mm(297)
        s.top_margin = Mm(20)
        s.bottom_margin = Mm(20)
        s.left_margin = Mm(30)
        s.right_margin = Mm(15)
        # Очистка колонтитулов
        s.header.is_linked_to_previous = False
        s.footer.is_linked_to_previous = False
        for p in s.header.paragraphs:
            p.text = ""
        for p in s.footer.paragraphs:
            p.text = ""

    # Настройка базового стиля Обычный (Normal)
    style_normal = doc.styles['Normal']
    style_normal.font.name = 'Times New Roman'
    style_normal.font.size = Pt(14)
    style_normal.font.color.rgb = RGBColor(0, 0, 0)
    style_normal.paragraph_format.line_spacing = 1.5
    style_normal.paragraph_format.space_before = Pt(0)
    style_normal.paragraph_format.space_after = Pt(0)

    # Вспомогательные функции добавления текста
    def add_p(text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_before=0, space_after=0, bold=False, italic=False, indent=True, size=14):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.line_spacing = 1.5
        if indent:
            p.paragraph_format.first_line_indent = Mm(12.5)
        else:
            p.paragraph_format.first_line_indent = Mm(0)
        if text:
            run = p.add_run(text)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(size)
            run.font.color.rgb = RGBColor(0, 0, 0)
            run.bold = bold
            run.italic = italic
        return p

    def add_h(text, level=1):
        p = doc.add_paragraph()
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Mm(0)
        
        if level == 1:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(6)
            run = p.add_run(text)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(14)
            run.bold = True
            run.font.color.rgb = RGBColor(0, 0, 0)
            p.style = doc.styles['Heading 1']
        elif level == 2:
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_before = Pt(10)
            p.paragraph_format.space_after = Pt(4)
            p.paragraph_format.first_line_indent = Mm(12.5)
            run = p.add_run(text)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(13)
            run.bold = True
            run.font.color.rgb = RGBColor(0, 0, 0)
            p.style = doc.styles['Heading 2']
        elif level == 3:
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_before = Pt(6)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.first_line_indent = Mm(12.5)
            run = p.add_run(text)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(12)
            run.bold = True
            run.font.color.rgb = RGBColor(0, 0, 0)
            p.style = doc.styles['Heading 3']
        return p

    def add_bullet(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Mm(12.5)
        run = p.add_run("— " + text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.font.color.rgb = RGBColor(0, 0, 0)
        return p

    def format_table(table, col_widths, align_center=False):
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        # Установка тонких черных границ 1pt без фона
        tblPr = table._tbl.tblPr
        tblBorders = parse_xml(
            f'<w:tblBorders {nsdecls("w")}>'
            f'<w:top w:val="single" w:sz="8" w:space="0" w:color="000000"/>'
            f'<w:left w:val="single" w:sz="8" w:space="0" w:color="000000"/>'
            f'<w:bottom w:val="single" w:sz="8" w:space="0" w:color="000000"/>'
            f'<w:right w:val="single" w:sz="8" w:space="0" w:color="000000"/>'
            f'<w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'<w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            f'</w:tblBorders>'
        )
        tblPr.append(tblBorders)

        for row in table.rows:
            trPr = row._tr.get_or_add_trPr()
            trPr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
            for idx, cell in enumerate(row.cells):
                cell.width = col_widths[idx]
                tcPr = cell._tc.get_or_add_tcPr()
                tcMar = parse_xml(
                    f'<w:tcMar {nsdecls("w")}>'
                    f'<w:top w:w="120" w:type="dxa"/>'
                    f'<w:bottom w:w="120" w:type="dxa"/>'
                    f'<w:left w:w="160" w:type="dxa"/>'
                    f'<w:right w:w="160" w:type="dxa"/>'
                    f'</w:tcMar>'
                )
                tcPr.append(tcMar)
                for p in cell.paragraphs:
                    p.paragraph_format.line_spacing = 1.15
                    p.paragraph_format.space_before = Pt(1)
                    p.paragraph_format.space_after = Pt(1)
                    p.paragraph_format.first_line_indent = Mm(0)
                    if align_center:
                        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    for r in p.runs:
                        r.font.name = 'Times New Roman'
                        r.font.size = Pt(10.5)
                        r.font.color.rgb = RGBColor(0, 0, 0)

    def add_table_caption(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.first_line_indent = Mm(0)
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
        run.font.color.rgb = RGBColor(0, 0, 0)
        run.bold = True
        return p

