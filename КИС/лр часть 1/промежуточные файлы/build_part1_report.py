    add_p("по лабораторным работам", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=4, bold=True, indent=False, size=14)
    add_p("по дисциплине «Корпоративные информационные системы»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=6, bold=True, indent=False, size=14)
    add_p("ЧАСТЬ 1", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=14, bold=True, indent=False, size=15)

    add_p("Тема: «Проектирование корпоративной информационной системы автосервиса чип-тюнинга BMW102: технико-экономическая характеристика объекта автоматизации и реляционная модель данных (ERD)»", align=WD_ALIGN_PARAGRAPH.CENTER, space_after=40, italic=True, indent=False, size=13)

