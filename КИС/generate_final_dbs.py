def add_h(text, level=1):
    p = doc.add_paragraph(style=f'Heading {level}')
    p.text = text
    p.paragraph_format.keep_with_next = True
    return p

def add_p(text, style='Normal', bold_prefix="", space_after=4):
    p = doc.add_paragraph(style=style)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if bold_prefix:
        r_pre = p.add_run(bold_prefix)
        r_pre.bold = True
    p.add_run(text)
    return p

def add_bullet(text, bold_prefix=""):
    return add_p(text, style='IP_20_List1', bold_prefix=bold_prefix, space_after=2)

def add_caption(text):
    p = doc.add_paragraph(style='Caption')
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    p.text = text
    return p

def add_img_figure(img_path, caption_text, width_inches=6.0):
    if os.path.exists(img_path):
        p_img = doc.add_paragraph(style='IP_33_ShapeName')
        p_img.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.CENTER
        p_img.paragraph_format.space_before = Pt(8)
        p_img.paragraph_format.space_after = Pt(2)
        p_img.paragraph_format.keep_with_next = True
        run = p_img.add_run()
        run.add_picture(img_path, width=Inches(width_inches))
        add_caption(caption_text)
    else:
        print(f"WARNING: Image not found: {img_path}")

def create_styled_table(rows, cols, col_widths=None):
    tbl = doc.add_table(rows=rows, cols=cols)
    tbl.style = doc.styles['IP_40_Table1']
    tbl.alignment = docx.enum.table.WD_TABLE_ALIGNMENT.CENTER
    if col_widths:
        for r in tbl.rows:
            for ci, w in enumerate(col_widths):
                r.cells[ci].width = Inches(w)
    return tbl

