def repack_docx(source_docx, dest_docx):
    with zipfile.ZipFile(source_docx, 'r') as zin, zipfile.ZipFile(dest_docx, 'w', compression=zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            fname = item.filename
            data = zin.read(fname)
            
            # Replace logos
            if fname == 'word/media/image1.png':
                data = uunit_bytes
            elif fname == 'word/media/image2.png':
                data = exec_bytes
            # Replace footer3
            elif fname == 'word/footer3.xml':
                data = footer3_bytes
            # Replace headers so every header has the exact same 3-column table with both logos and STYLEREF
            elif fname in ['word/header2.xml', 'word/header4.xml', 'word/header5.xml']:
                data = clean_h_xml
            elif fname in ['word/_rels/header2.xml.rels', 'word/_rels/header4.xml.rels', 'word/_rels/header5.xml.rels']:
                data = clean_h_rels
                
            zout.writestr(item, data)
    print(f"Repacked cleanly into: {dest_docx}")

