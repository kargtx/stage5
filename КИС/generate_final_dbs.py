def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)

def set_cell_background(cell, fill_hex):
    shading_elm = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{fill_hex}"/>')
    cell._tc.get_or_add_tcPr().append(shading_elm)

def set_cell_text(cell, text, bold=False, italic=False, size_pt=9.5, align='left', font_name='Arial'):
    cell.text = ''
    p = cell.paragraphs[0]
    p.style = doc.styles['IP_41_TableText']
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.05
    if align == 'center':
        p.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.CENTER
    elif align == 'right':
        p.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.RIGHT
    else:
        p.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.font.name = font_name
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.italic = italic
    return p

